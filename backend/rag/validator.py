"""
Answer Validation Layer (Phase 3.5 — Strict Grounding & Hallucination Fix).

Performs lightweight verification of Gemini's generated answer against the retrieved
context before saving or displaying it to the user.

Checks:
1. Cited files: any backticked file path must exist in the retrieved context.
2. Cited commits: any commit SHA mentioned must exist in the retrieved commit memories.
3. Insufficient context detection: if the model claims something cannot be found,
   ensures it does not also invent hypothetical details.

If validation fails, returns a grounded insufficient-context fallback response.
"""

import re
import logging
from typing import Optional

logger = logging.getLogger(__name__)

# Pattern to detect backticked file paths (e.g. `backend/auth/views.py` or `src/App.tsx`)
_FILE_PATH_RE = re.compile(r'`([a-zA-Z0-9_\-./]+\.[a-zA-Z0-9]{1,8})`')

# Pattern to detect 7-40 char hex commit SHAs
_COMMIT_SHA_RE = re.compile(r'\b([0-9a-f]{7,40})\b', re.IGNORECASE)

# Known external packages, language libraries, or general tooling to ignore in file path checks
_COMMON_EXTERNALS = {
    'package.json', 'tsconfig.json', 'docker-compose.yml', 'dockerfile',
    '.env', '.gitignore', 'readme.md',
    'python', 'javascript', 'typescript', 'react', 'django',
}


def validate_answer(
    answer: str,
    context_chunks: list[dict],
    query_type: str = 'general',
) -> tuple[bool, str, list[str]]:
    """
    Validate that claims, files, and commits in the answer are grounded in context_chunks.

    Args:
        answer: The text generated by Gemini.
        context_chunks: The list of chunk dicts that were passed in the system context.
        query_type: The detected QueryType string.

    Returns:
        (is_valid, final_answer, list_of_validation_errors)
    """
    if not context_chunks:
        # If no context was provided, the answer MUST state insufficiency
        if "couldn't find" in answer.lower() or "insufficient" in answer.lower() or "not enough" in answer.lower():
            return True, answer, []
        return False, (
            "I couldn't find enough verified evidence in the indexed repository to answer this confidently."
        ), ['generation without context']

    # 1. Build sets of valid entities from context_chunks
    valid_file_paths = set()
    valid_file_names = set()
    valid_commit_shas = set()
    valid_symbols = set()
    all_context_content = []

    for c in context_chunks:
        content = c.get('content', '')
        if content:
            all_context_content.append(content.lower())

        fp = c.get('file_path', '')
        if fp:
            valid_file_paths.add(fp.lower())
            filename = fp.rsplit('/', 1)[-1].lower()
            valid_file_names.add(filename)
            # Without extension
            valid_file_names.add(filename.rsplit('.', 1)[0])

        sym = c.get('symbol_name', '')
        if sym:
            valid_symbols.add(sym.lower())
            if '.' in sym:
                valid_symbols.add(sym.rsplit('.', 1)[-1].lower())

        sha = c.get('commit_sha', '')
        if sha:
            valid_commit_shas.add(sha.lower())
            valid_commit_shas.add(sha[:7].lower())

    full_context_text = " ".join(all_context_content)
    errors = []

    # 2. Check cited file paths
    cited_files = _FILE_PATH_RE.findall(answer)
    for cited in cited_files:
        cited_lower = cited.lower()
        fn = cited_lower.rsplit('/', 1)[-1]

        # Ignore standard config/library filenames
        if fn in _COMMON_EXTERNALS or fn.startswith('http'):
            continue

        # Check if cited file matches any retrieved file path, filename,
        # OR appears verbatim in the code content of the retrieved chunks
        matches = (
            cited_lower in valid_file_paths
            or fn in valid_file_names
            or any(cited_lower in v for v in valid_file_paths)
            or any(v in cited_lower for v in valid_file_paths)
            or cited_lower in full_context_text
            or (len(fn) >= 4 and fn in full_context_text)
        )

        # Allow stating that a file does NOT exist or is absent
        is_negation = any(
            neg in answer.lower()
            for neg in [
                f'no `{cited_lower}`', f'not contain `{cited_lower}`',
                f'`{cited_lower}` does not exist', f'`{cited_lower}` is not present',
                f'without `{cited_lower}`', f'neither `{cited_lower}`',
                f'no `{fn}`', f'not contain `{fn}`',
            ]
        )

        if not matches and not is_negation:
            errors.append(f"Answer cited file '{cited}' which does not exist in retrieved context")

    # 3. Check cited commit SHAs for history queries
    if query_type == 'history' or 'commit' in answer.lower():
        cited_shas = _COMMIT_SHA_RE.findall(answer)
        for sha in cited_shas:
            sha_lower = sha.lower()
            # Exclude words or numbers that happen to be 7 hex chars
            if sha_lower.isdigit() or len(sha_lower) < 7:
                continue
            if valid_commit_shas and not any(sha_lower.startswith(v) or v.startswith(sha_lower) for v in valid_commit_shas):
                errors.append(f"Answer cited commit SHA '{sha}' which does not exist in retrieved context")

    if errors:
        logger.warning('Grounding validation failed for query (%s): %s', query_type, errors)
        grounded_fallback = (
            "I couldn't find enough verified evidence in the indexed repository to answer this confidently. "
            "The retrieved code and history did not contain sufficient verified context."
        )
        return False, grounded_fallback, errors

    return True, answer, []
